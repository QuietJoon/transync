    /// Comrak stops resolving references once their expansions pass
    /// `max(input bytes, 100_000)`, so a long, reference-dense source and its
    /// longer translation stop at DIFFERENT references. The scan must compare
    /// the two documents under one budget, or every such document would read
    /// as a destination change the cascade cannot undo.
    #[test]
    fn a_reference_dense_document_is_compared_under_one_expansion_budget() {
        let url = format!("https://example.com/{}", "a".repeat(1_000));
        let mut src = format!("[r]: {url}\n\n");
        let blocks = 200;
        for i in 0..blocks {
            src.push_str(&format!(
                "Use [a][r] number {i:03}: {}\n\n",
                "x".repeat(600)
            ));
        }
        let doc = parse(&src).expect("source parses");
        assert_eq!(
            doc.blocks.len(),
            blocks,
            "fixture sanity: one block per use"
        );
        assert!(
            src.len() > 100_000 && blocks * url.len() > src.len() * 3 / 2,
            "fixture sanity: the expansions outrun even the longer document"
        );
        let payloads: Vec<String> = (0..blocks)
            .map(|i| format!("사용 [가][r] 번호 {i:03}: {}", "y".repeat(800)))
            .collect();
        let pairs: Vec<(usize, &str)> = payloads.iter().map(|p| p.as_str()).enumerate().collect();
        let (md, offsets) = regen_with(&doc, &pairs);
        assert!(
            md.len() > src.len(),
            "fixture sanity: the translation is longer"
        );
        enforced(&doc, &md, &offsets).expect("every use resolves to the same destination");
    }

