    // R0013-0003, scan 4: the document-level backstop for link and image
    // destinations. Each regenerated document below keeps every top-level
    // kind, the block count and every list's item count, so scans 1–3 pass
    // it; what changed is where a link goes, which only resolution against
    // the WHOLE document can see — a definition inside a blockquote, a list
    // item or ahead of a paragraph's text resolves document-wide.

    /// The gate as a run with the shipped default profile drives it
    /// (`preserve_urls = true`).
    fn enforced(doc: &Document, md: &str, offsets: &BlockOffsets) -> Result<(), ReparseFailure> {
        reparse_full(doc, md, offsets, true)
    }

    /// Regenerate `src` with the given block payloads (by block index).
    fn regen_with(doc: &Document, payloads: &[(usize, &str)]) -> (String, BlockOffsets) {
        let map: std::collections::HashMap<BlockId, String> = payloads
            .iter()
            .map(|(i, p)| (doc.blocks[*i].block_id.clone(), (*p).to_string()))
            .collect();
        regenerate(doc, &map)
    }

